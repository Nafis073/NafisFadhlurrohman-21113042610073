places = ["Jepang", "Swiss", "Korea Selatan", "Turki", "Australia"]

print("Daftar asli:", places)

print("Urutan alfabetis:", sorted(places))

print("Daftar asli:", places)

print("Urutan terbalik alfabetis:", sorted(places, reverse=True))

places.reverse()
print("Dibalik:", places)

places.reverse()
print("Kembali seperti semula:", places)

places.sort()
print("Diurutkan:", places)

places.sort(reverse=True)
print("Diurutkan terbalik:", places)